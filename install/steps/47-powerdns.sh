# shellcheck shell=bash
# Tela's own authoritative DNS server. Only with --with-dns-server: most
# people keep their domains at Cloudflare or their registrar.
if [[ "${TELA_DNS_SERVER:-0}" != "1" ]]; then
  return 0
fi

step "Installing the DNS server (PowerDNS)"

# systemd-resolved's stub listener holds 127.0.0.53:53, which stops PowerDNS
# from listening on all addresses. Turn the stub off; the server keeps resolving
# names through resolved's regular resolv.conf.
if systemctl is-active --quiet systemd-resolved; then
  install -d -m 0755 /etc/systemd/resolved.conf.d
  if write_if_changed /etc/systemd/resolved.conf.d/tela.conf <<'EOF'; then
# Managed by Tela: PowerDNS answers on port 53.
[Resolve]
DNSStubListener=no
EOF
    ln -sf /run/systemd/resolve/resolv.conf /etc/resolv.conf
    run systemctl restart systemd-resolved
    ok "Freed port 53 (systemd-resolved stub listener off)"
  fi
fi

apt_install pdns-server pdns-backend-bind

install -d -m 0755 /etc/powerdns/tela /etc/powerdns/tela/zones
if [[ ! -f /etc/powerdns/tela/named.conf ]]; then
  echo "// Generated by Tela. Changes here are overwritten." >/etc/powerdns/tela/named.conf
fi

write_if_changed /etc/powerdns/pdns.d/tela.conf <<'EOF' || true
# Managed by Tela. Zones are written by tela-agent to /etc/powerdns/tela/.
launch=bind
bind-config=/etc/powerdns/tela/named.conf
local-address=0.0.0.0, ::
api=no
EOF

enable_service pdns
run systemctl restart pdns
for _ in $(seq 1 15); do
  if pdns_control rping >/dev/null 2>&1; then
    break
  fi
  sleep 1
done
pdns_control rping >/dev/null 2>&1 || die "PowerDNS did not start; check: journalctl -u pdns -n 50"

# Zones Tela already knows about are written by tela_agent.setup (step 55).
ok "PowerDNS answers on port 53; add zones under DNS in the panel"
