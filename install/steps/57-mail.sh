# shellcheck shell=bash
step "Installing the mail server"

# Answer Postfix's setup questions up front (the actual configuration is Tela's).
mailname="$(hostname -f 2>/dev/null || hostname)"
debconf-set-selections <<EOF2
postfix postfix/main_mailer_type select Internet Site
postfix postfix/mailname string $mailname
EOF2

apt_install postfix dovecot-core dovecot-imapd dovecot-pop3d dovecot-lmtpd \
  rspamd redis-server ca-certificates
ok "Postfix, Dovecot, Rspamd and Redis installed"

# All mailboxes belong to one system user.
if ! id vmail >/dev/null 2>&1; then
  if getent passwd 5000 >/dev/null || getent group 5000 >/dev/null; then
    run useradd --system --user-group --home-dir /var/vmail --no-create-home \
      --shell /usr/sbin/nologin vmail
  else
    run useradd --system --uid 5000 --user-group --home-dir /var/vmail --no-create-home \
      --shell /usr/sbin/nologin vmail
  fi
fi
install -d -m 0750 -o vmail -g vmail /var/vmail
install -d -m 0755 -o root -g root /etc/postfix/tela
install -d -m 0750 -o root -g dovecot /etc/dovecot/tela
install -d -m 0750 -o _rspamd -g _rspamd /var/lib/rspamd/dkim
install -d -m 0700 -o root -g root "$TELA_ETC/mail"

# Tela writes a complete dovecot.conf; keep the packaged one for reference.
if [[ -f /etc/dovecot/dovecot.conf && ! -f /etc/dovecot/dovecot.conf.tela-orig ]] \
  && ! grep -q "Generated by Tela" /etc/dovecot/dovecot.conf; then
  cp -p /etc/dovecot/dovecot.conf /etc/dovecot/dovecot.conf.tela-orig
fi

enable_service redis-server
run systemctl start redis-server
enable_service postfix
run systemctl start postfix

run env PYTHONPATH="$TELA_DIR/src" "$TELA_VENV/bin/python" -m tela_agent.mailsetup

for unit in dovecot rspamd; do
  enable_service "$unit"
  run systemctl restart "$unit"
done
run systemctl reload-or-restart postfix
ok "Mail server running (SMTP 25, submission 587/465, IMAP 993/143, POP3 995/110)"

# Renewed certificates for the mail host name: Postfix and Dovecot load them on reload.
write_if_changed /etc/letsencrypt/renewal-hooks/deploy/tela-reload-mail.sh <<'EOF2' || true
#!/bin/sh
# Installed by Tela: load a renewed mail server certificate.
case "$RENEWED_LINEAGE" in
  */tela-mail) systemctl reload-or-restart postfix dovecot ;;
esac
exit 0
EOF2
chmod 0755 /etc/letsencrypt/renewal-hooks/deploy/tela-reload-mail.sh

# Many home and cloud connections block outgoing port 25.
if ! timeout 8 bash -c 'exec 3<>/dev/tcp/gmail-smtp-in.l.google.com/25' 2>/dev/null; then
  warn "Outgoing port 25 seems blocked. Sending mail to other servers won't work until"
  warn "your provider unblocks it (receiving and webmail still work)."
fi
