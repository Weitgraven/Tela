"""Mail server configuration rendered from Tela's mail state.

Pure functions: given the domains (with their mailboxes and aliases) they
return file contents. tela_agent.actions.mail writes them and reloads services.

A domain looks like:

    {"domain": "example.com", "dkim_selector": "tela",
     "mailboxes": [{"local": "info", "name": "", "password": "$6$...",
                    "quota_mb": 1024, "enabled": True}],
     "aliases": [{"local": "sales", "destinations": ["info@example.com"]},
                 {"local": "*", "destinations": ["info@example.com"]}]}
"""

from __future__ import annotations

import secrets
from pathlib import Path
from typing import Any

from .sha512crypt import sha512_crypt

HEADER = "# Generated by Tela. Changes here are overwritten.\n"
VMAIL_ROOT = Path("/var/vmail")


def address(local: str, domain: str) -> str:
    return f"{local}@{domain}"


def maildir_home(local: str, domain: str, root: Path = VMAIL_ROOT) -> Path:
    return root / domain / local


# ---------------------------------------------------------------------------
# Postfix lookup tables (texthash: read directly, no postmap needed)
# ---------------------------------------------------------------------------


def postfix_maps(domains: list[dict[str, Any]]) -> dict[str, str]:
    """Return {file name: content} for the Postfix lookup tables."""
    domain_lines, mailbox_lines, alias_lines, sender_lines = [], [], [], []
    for d in sorted(domains, key=lambda d: d["domain"]):
        name = d["domain"]
        domain_lines.append(f"{name} OK")
        mailboxes = sorted(d["mailboxes"], key=lambda m: m["local"])
        has_catchall = any(a["local"] == "*" for a in d["aliases"])
        for m in mailboxes:
            addr = address(m["local"], name)
            mailbox_lines.append(f"{addr} {name}/{m['local']}/")
            sender_lines.append(f"{addr} {addr}")
            if has_catchall:
                # Without this, the catch-all would also swallow real mailboxes.
                alias_lines.append(f"{addr} {addr}")
        local_mailboxes = {address(m["local"], name) for m in mailboxes}
        senders: dict[str, list[str]] = {}
        for a in sorted(d["aliases"], key=lambda a: (a["local"] == "*", a["local"])):
            source = f"@{name}" if a["local"] == "*" else address(a["local"], name)
            alias_lines.append(f"{source} {','.join(a['destinations'])}")
            if a["local"] != "*":
                # Mailboxes that receive an alias may also send as it.
                owners = [dest for dest in a["destinations"] if dest in local_mailboxes]
                if owners:
                    senders[source] = owners
        sender_lines += [f"{src} {','.join(owners)}" for src, owners in senders.items()]
    return {
        "domains": HEADER + "".join(f"{line}\n" for line in domain_lines),
        "mailboxes": HEADER + "".join(f"{line}\n" for line in mailbox_lines),
        "aliases": HEADER + "".join(f"{line}\n" for line in alias_lines),
        "senders": HEADER + "".join(f"{line}\n" for line in sender_lines),
    }


