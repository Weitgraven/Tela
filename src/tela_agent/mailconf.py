def dovecot_users(domains: list[dict[str, Any]], uid: int, gid: int, major_minor: tuple[int, int],
                  root: Path = VMAIL_ROOT) -> str:  # fmt: skip
    """passwd-file used as both passdb and userdb."""
    lines = []
    for d in sorted(domains, key=lambda d: d["domain"]):
        for m in sorted(d["mailboxes"], key=lambda m: m["local"]):
            addr = address(m["local"], d["domain"])
            # A disabled mailbox still receives mail but can't sign in: its hash is
            # replaced by the hash of a random secret nobody knows.
            enabled = m.get("enabled", True)
            hashed = m["password"] if enabled else sha512_crypt(secrets.token_hex(24))
            password = "{SHA512-CRYPT}" + hashed
            home = maildir_home(m["local"], d["domain"], root)
            quota = int(m.get("quota_mb") or 0)
            extra = ""
            if quota > 0:
                extra = (
                    f"userdb_quota_storage_size={quota}M"
                    if major_minor >= (2, 4)
                    else f"userdb_quota_rule=*:storage={quota}M"
                )
            lines.append(f"{addr}:{password}:{uid}:{gid}::{home}::{extra}")
    return "".join(f"{line}\n" for line in lines)


