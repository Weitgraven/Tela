"""OpenLiteSpeed configuration.

Tela owns three things in the OpenLiteSpeed tree and never edits anything else:

* one include line in conf/httpd_config.conf, between marker comments,
  pointing at conf/tela/*.conf;
* conf/tela/: one `virtualhost` block per site plus `zz-listeners.conf`
  (named so it loads after the virtual hosts it maps);
* conf/vhosts/<domain>/vhconf.conf for each site.

All of it is regenerated from the site state files on every change, so the
web server config can always be rebuilt from scratch.
"""

from __future__ import annotations

import contextlib
import re
from collections.abc import Callable, Iterable
from dataclasses import dataclass, field
from pathlib import Path

from .settings import Paths
from .sysops import write_atomic

INCLUDE_BEGIN = "# >>> Tela: managed include, do not edit >>>"
INCLUDE_END = "# <<< Tela <<<"
HEADER = "# Generated by Tela. Changes here are overwritten.\n"

# Stock blocks from a fresh OpenLiteSpeed install that conflict with Tela's.
STOCK_BLOCKS = {("listener", "Default"), ("virtualhost", "Example")}


@dataclass
class Site:
    domain: str
    user: str
    php_version: str
    home: Path
    aliases: list[str] = field(default_factory=list)
    force_https: bool = False
    ssl_cert: str | None = None
    ssl_key: str | None = None
    ssl_names: list[str] = field(default_factory=list)
    ssl_expires_at: int | None = None
    created_at: int = 0
    databases: list[str] = field(default_factory=list)

    @property
    def processor(self) -> str:
        return "tela_" + re.sub(r"[^a-z0-9]", "", self.user)

    @property
    def all_names(self) -> list[str]:
        return [self.domain, *self.aliases]

    @property
    def acme_dir(self) -> Path:
        return self.home / ".acme"

    def to_dict(self) -> dict:
        return {
            "domain": self.domain,
            "user": self.user,
            "php_version": self.php_version,
            "home": str(self.home),
            "aliases": self.aliases,
            "force_https": self.force_https,
            "ssl_cert": self.ssl_cert,
            "ssl_key": self.ssl_key,
            "ssl_names": self.ssl_names,
            "ssl_expires_at": self.ssl_expires_at,
            "created_at": self.created_at,
            "databases": self.databases,
        }

    @classmethod
    def from_dict(cls, data: dict) -> Site:
        return cls(
            domain=data["domain"],
            user=data["user"],
            php_version=data["php_version"],
            home=Path(data["home"]),
            aliases=list(data.get("aliases", [])),
            force_https=bool(data.get("force_https", False)),
            ssl_cert=data.get("ssl_cert"),
            ssl_key=data.get("ssl_key"),
            ssl_names=list(data.get("ssl_names", [])),
            ssl_expires_at=data.get("ssl_expires_at"),
            created_at=int(data.get("created_at", 0)),
            databases=list(data.get("databases", [])),
        )


# ---------------------------------------------------------------------------
# Parsing
# ---------------------------------------------------------------------------

_BLOCK_START = re.compile(r"^\s*(\S+)(?:\s+(\S+))?\s*\{\s*$")
_HEREDOC = re.compile(r"<<<(\w+)\s*$")


def strip_blocks(text: str, remove: Callable[[str, str | None], bool]) -> str:
    """Remove top-level `kind name { ... }` blocks for which remove(kind, name) is true.

    Understands nesting and `<<<MARK ... MARK` heredocs (used for rewrite rules,
    which may contain braces).
    """
    out: list[str] = []
    depth = 0
    skipping = False
    heredoc: str | None = None
    for line in text.splitlines(keepends=True):
        stripped = line.strip()
        if heredoc is not None:
            if stripped == heredoc:
                heredoc = None
            if not skipping:
                out.append(line)
            continue
        if match := _HEREDOC.search(stripped):
            heredoc = match.group(1)
        elif match := _BLOCK_START.match(line):
            if depth == 0 and remove(match.group(1), match.group(2)):
                skipping = True
            depth += 1
        elif stripped == "}":
            depth -= 1
            if depth == 0 and skipping:
                skipping = False
                continue
        if not skipping:
            out.append(line)
    return "".join(out)


def ensure_include(text: str, include_dir: Path) -> str:
    """Return httpd_config.conf text with stock listeners removed and Tela's include present."""
    text = strip_blocks(text, lambda kind, name: (kind, name) in STOCK_BLOCKS)
    if INCLUDE_BEGIN in text:
        text = re.sub(
            re.escape(INCLUDE_BEGIN) + r".*?" + re.escape(INCLUDE_END) + r"\n?",
            "",
            text,
            flags=re.S,
        )
    block = f"{INCLUDE_BEGIN}\ninclude {include_dir}/*.conf\n{INCLUDE_END}\n"
    return text.rstrip("\n") + "\n\n" + block


# ---------------------------------------------------------------------------
# Rendering
# ---------------------------------------------------------------------------


def _kv(key: str, value: object, indent: int = 2) -> str:
    return f"{' ' * indent}{key:<24}{value}\n"


def render_vhost_block(site: Site, paths: Paths) -> str:
    conf = paths.vhost_conf_root / site.domain / "vhconf.conf"
    return (
        HEADER
        + f"virtualhost {site.domain} {{\n"
        + _kv("vhRoot", site.home)
        + _kv("configFile", conf)
        + _kv("allowSymbolLink", 1)
        + _kv("enableScript", 1)
        + _kv("restrained", 1)
        + _kv("setUIDMode", 2)
        + "}\n"
    )


def render_vhconf(site: Site, paths: Paths) -> str:
    lsphp = paths.ols_root / f"lsphp{site.php_version.replace('.', '')}" / "bin" / "lsphp"
    lines = [
        HEADER,
        _kv("docRoot", "$VH_ROOT/public_html", 0),
        _kv("vhDomain", site.domain, 0),
    ]
    if site.aliases:
        lines.append(_kv("vhAliases", ", ".join(site.aliases), 0))
    lines += [
        _kv("enableGzip", 1, 0),
        "\nindex {\n",
        _kv("useServer", 0),
        _kv("indexFiles", "index.php, index.html, index.htm"),
        _kv("autoIndex", 0),
        "}\n",
        f"\nerrorlog $VH_ROOT/logs/{site.domain}.error.log {{\n",
        _kv("useServer", 0),
        _kv("logLevel", "WARN"),
        _kv("rollingSize", "10M"),
        _kv("keepDays", 14),
        "}\n",
        f"\naccesslog $VH_ROOT/logs/{site.domain}.access.log {{\n",
        _kv("useServer", 0),
        _kv("logFormat", '"%h %l %u %t \\"%r\\" %>s %b \\"%{Referer}i\\" \\"%{User-Agent}i\\""'),
        _kv("logHeaders", 5),
        _kv("rollingSize", "10M"),
        _kv("keepDays", 14),
        _kv("compressArchive", 1),
        "}\n",
        "\nscripthandler {\n",
        _kv("add", f"lsapi:{site.processor} php"),
        "}\n",
        f"\nextprocessor {site.processor} {{\n",
        _kv("type", "lsapi"),
        _kv("address", f"UDS://tmp/lshttpd/{site.processor}.sock"),
        _kv("maxConns", 10),
        _kv("env", "LSAPI_CHILDREN=10"),
        _kv("initTimeout", 60),
        _kv("retryTimeout", 0),
        _kv("persistConn", 1),
        _kv("pcKeepAliveTimeout", 1),
        _kv("respBuffer", 0),
        _kv("autoStart", 1),
        _kv("path", lsphp),
        _kv("extUser", site.user),
        _kv("extGroup", site.user),
        _kv("memSoftLimit", "2047M"),
        _kv("memHardLimit", "2047M"),
        _kv("procSoftLimit", 400),
        _kv("procHardLimit", 500),
        "}\n",
        # Let's Encrypt HTTP-01 challenges are answered from a directory only
        # root writes to, so a site can't interfere with its own validation.
        "\ncontext /.well-known/acme-challenge/ {\n",
        _kv("location", "$VH_ROOT/.acme/.well-known/acme-challenge/"),
        _kv("allowBrowse", 1),
        "  rewrite {\n",
        _kv("enable", 0, 4),
        "  }\n",
        _kv("addDefaultCharset", "off"),
        "}\n",
        "\nrewrite {\n",
        _kv("enable", 1),
        _kv("autoLoadHtaccess", 1),
    ]
    if site.force_https and site.ssl_cert:
        lines += [
            "  rules <<<END_rules\n",
            "RewriteCond %{HTTPS} !=on\n",
            "RewriteCond %{REQUEST_URI} !^/\\.well-known/acme-challenge/\n",
            "RewriteRule ^/?(.*)$ https://%{HTTP_HOST}/$1 [R=301,L]\n",
            "END_rules\n",
        ]
    lines.append("}\n")
    if site.ssl_cert and site.ssl_key:
        lines += [
            "\nvhssl {\n",
            _kv("keyFile", site.ssl_key),
            _kv("certFile", site.ssl_cert),
            _kv("certChain", 1),
            _kv("sslProtocol", 24),
            _kv("enableECDHE", 1),
            _kv("renegProtection", 1),
            _kv("sslSessionCache", 1),
            _kv("enableSpdy", 15),
            _kv("enableStapling", 1),
            _kv("ocspRespMaxAge", 86400),
            "}\n",
        ]
    return "".join(lines)


def render_listeners(sites: Iterable[Site], paths: Paths) -> str:
    maps = "".join(
        _kv("map", f"{site.domain} {', '.join(site.all_names)}")
        for site in sorted(sites, key=lambda s: s.domain)
    )
    return (
        HEADER
        + "listener TelaHTTP {\n"
        + _kv("address", "*:80")
        + _kv("secure", 0)
        + maps
        + "}\n\n"
        + "listener TelaHTTPS {\n"
        + _kv("address", "*:443")
        + _kv("secure", 1)
        + _kv("keyFile", paths.default_key)
        + _kv("certFile", paths.default_cert)
        + _kv("certChain", 0)
        + _kv("sslProtocol", 24)
        + _kv("enableECDHE", 1)
        + _kv("renegProtection", 1)
        + _kv("sslSessionCache", 1)
        + _kv("enableSpdy", 15)
        + maps
        + "}\n"
    )


# ---------------------------------------------------------------------------
# phpMyAdmin: its own virtual host on its own HTTPS port, PHP running as the
# dedicated tela-pma user, reusing the panel's certificate.
# ---------------------------------------------------------------------------

PMA_VHOST = "TelaPhpMyAdmin"


def _pma_php(paths: Paths) -> Path:
    preferred = paths.ols_root / f"lsphp{paths.default_php.replace('.', '')}" / "bin" / "lsphp"
    if preferred.exists():
        return preferred
    installed = sorted(paths.ols_root.glob("lsphp[0-9][0-9]/bin/lsphp"))
    return installed[-1] if installed else preferred


def render_pma_vhost_block(paths: Paths) -> str:
    return (
        HEADER
        + f"virtualhost {PMA_VHOST} {{\n"
        + _kv("vhRoot", f"{paths.pma_root}/")
        + _kv("configFile", paths.vhost_conf_root / PMA_VHOST / "vhconf.conf")
        + _kv("allowSymbolLink", 0)
        + _kv("enableScript", 1)
        + _kv("restrained", 1)
        + "}\n"
    )


def render_pma_vhconf(paths: Paths) -> str:
    return "".join(
        [
            HEADER,
            _kv("docRoot", "$VH_ROOT", 0),
            "\nindex {\n",
            _kv("useServer", 0),
            _kv("indexFiles", "index.php"),
            _kv("autoIndex", 0),
            "}\n",
            "\nscripthandler {\n",
            _kv("add", "lsapi:tela_pma php"),
            "}\n",
            "\nextprocessor tela_pma {\n",
            _kv("type", "lsapi"),
            _kv("address", "UDS://tmp/lshttpd/tela_pma.sock"),
            _kv("maxConns", 5),
            _kv("env", "LSAPI_CHILDREN=5"),
            _kv("initTimeout", 60),
            _kv("retryTimeout", 0),
            _kv("persistConn", 1),
            _kv("respBuffer", 0),
            _kv("autoStart", 1),
            _kv("path", _pma_php(paths)),
            _kv("extUser", paths.pma_user),
            _kv("extGroup", paths.pma_user),
            _kv("memSoftLimit", "1024M"),
            _kv("memHardLimit", "1024M"),
            "}\n",
            # Never serve phpMyAdmin's internals or temporary files directly.
            "".join(
                f"\ncontext /{d}/ {{\n" + _kv("allowBrowse", 0) + "}\n"
                for d in ("libraries", "src", "templates", "vendor", "tmp", "setup", "sql")
            ),
            "\nrewrite {\n",
            _kv("enable", 0),
            "}\n",
            # Sessions in a directory only phpMyAdmin's PHP user can use.
            "\nphpIniOverride {\n",
            f"php_admin_value session.save_path {paths.pma_tokens.parent / 'sessions'}\n",
            "php_admin_value upload_max_filesize 256M\n",
            "php_admin_value post_max_size 256M\n",
            "php_admin_value max_execution_time 600\n",
            "}\n",
        ]
    )


def render_pma_listener(paths: Paths) -> str:
    return (
        "\nlistener TelaPhpMyAdmin {\n"
        + _kv("address", f"*:{paths.pma_port}")
        + _kv("secure", 1)
        + _kv("keyFile", paths.panel_key)
        + _kv("certFile", paths.panel_cert)
        + _kv("certChain", 0)
        + _kv("sslProtocol", 24)
        + _kv("enableECDHE", 1)
        + _kv("renegProtection", 1)
        + _kv("sslSessionCache", 1)
        + _kv("map", f"{PMA_VHOST} *")
        + "}\n"
    )


# ---------------------------------------------------------------------------
# Writing
# ---------------------------------------------------------------------------


def desired_files(sites: list[Site], paths: Paths) -> dict[Path, str]:
    files: dict[Path, str] = {}
    for site in sites:
        files[paths.tela_conf_dir / f"vhost-{site.domain}.conf"] = render_vhost_block(site, paths)
        files[paths.vhost_conf_root / site.domain / "vhconf.conf"] = render_vhconf(site, paths)
    listeners = render_listeners(sites, paths)
    if paths.pma_installed:
        files[paths.tela_conf_dir / "phpmyadmin.conf"] = render_pma_vhost_block(paths)
        files[paths.vhost_conf_root / PMA_VHOST / "vhconf.conf"] = render_pma_vhconf(paths)
        listeners += render_pma_listener(paths)
    files[paths.tela_conf_dir / "zz-listeners.conf"] = listeners
    return files


def snapshot(paths: Paths, extra: Iterable[Path] = ()) -> dict[Path, str | None]:
    """Current content of every file Tela manages (None if missing), for rollback."""
    targets = {paths.httpd_config, paths.vhost_conf_root / PMA_VHOST / "vhconf.conf", *extra}
    if paths.tela_conf_dir.exists():
        targets.update(paths.tela_conf_dir.glob("*.conf"))
    return {p: (p.read_text() if p.exists() else None) for p in targets}


def restore(state: dict[Path, str | None]) -> None:
    for path, content in state.items():
        if content is None:
            path.unlink(missing_ok=True)
            if path.parent.name not in ("conf", "tela") and path.parent.exists():
                with contextlib.suppress(OSError):
                    path.parent.rmdir()  # only succeeds if empty
        else:
            write_atomic(path, content, 0o640 if path.suffix == ".conf" else 0o644)


def write(sites: list[Site], paths: Paths, removed: Iterable[str] = ()) -> list[Path]:
    """Write all config for `sites`; drop config of sites no longer present."""
    files = desired_files(sites, paths)
    if paths.httpd_config.exists():
        current = paths.httpd_config.read_text()
        updated = ensure_include(current, paths.tela_conf_dir)
        if updated != current:
            files[paths.httpd_config] = updated

    paths.tela_conf_dir.mkdir(parents=True, exist_ok=True)
    for path, content in files.items():
        write_atomic(path, content, 0o640)

    keep = {f"vhost-{s.domain}.conf" for s in sites} | {"zz-listeners.conf"}
    if paths.pma_installed:
        keep.add("phpmyadmin.conf")
    for stale in paths.tela_conf_dir.glob("*.conf"):
        if stale.name not in keep:
            stale.unlink()
    for domain in removed:
        vhconf = paths.vhost_conf_root / domain / "vhconf.conf"
        vhconf.unlink(missing_ok=True)
        if vhconf.parent.exists() and not any(vhconf.parent.iterdir()):
            vhconf.parent.rmdir()
    return list(files)
