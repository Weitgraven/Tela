"""Tela's own authoritative DNS: PowerDNS with the BIND backend.

Each zone is a zone file in <pdns_dir>/zones/, listed in <pdns_dir>/named.conf,
which PowerDNS is configured to read (see install/steps/47-powerdns.sh).
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

from .registry import ActionError
from .sysops import write_atomic


class PowerDNS:
    def __init__(self, base: Path) -> None:
        self.base = base

    @property
    def zones_dir(self) -> Path:
        return self.base / "zones"

    @property
    def named_conf(self) -> Path:
        return self.base / "named.conf"

    @property
    def available(self) -> bool:
        return self.named_conf.parent.exists() and shutil.which("pdns_control") is not None

    def zone_file(self, zone: str) -> Path:
        return self.zones_dir / f"{zone}.zone"

    def write(self, zones: dict[str, str]) -> None:
        """Write all zone files ({zone: content}) and the zone list."""
        self.zones_dir.mkdir(parents=True, exist_ok=True)
        for zone, content in zones.items():
            write_atomic(self.zone_file(zone), content, 0o644)
        listing = "// Generated by Tela. Changes here are overwritten.\n" + "".join(
            f'zone "{zone}" IN {{ type master; file "{self.zone_file(zone)}"; }};\n'
            for zone in sorted(zones)
        )
        write_atomic(self.named_conf, listing, 0o644)
        for stale in self.zones_dir.glob("*.zone"):
            if stale.name[: -len(".zone")] not in zones:
                stale.unlink()

    def reload(self, zone: str | None = None) -> None:
        """Pick up new or removed zones, and reload one zone's contents."""
        self._control(["rediscover"])
        if zone:
            self._control(["bind-reload-now", zone])

    @staticmethod
    def _control(args: list[str]) -> None:
        try:
            result = subprocess.run(["pdns_control", *args], capture_output=True, text=True,
                                    timeout=30, check=False)  # fmt: skip
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise ActionError(f"cannot reach PowerDNS: {exc}") from exc
        output = (result.stdout + result.stderr).strip()
        if result.returncode != 0 or "error" in output.lower() or "failed" in output.lower():
            raise ActionError(f"PowerDNS: {output or 'command failed'}")
